CREATE TABLE IF NOT EXISTS contracts (
    contract_id BIGINT PRIMARY KEY,
    issuer_id BIGINT,
    issuer_corporation_id BIGINT,
    assignee_id BIGINT,
    acceptor_id BIGINT,
    start_location_id BIGINT,
    end_location_id BIGINT,
    type VARCHAR(32),
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    availability VARCHAR(32),
    title TEXT,
    for_corporation BOOLEAN,
    date_issued DATETIME,
    date_expired DATETIME,
    date_accepted DATETIME,
    date_completed DATETIME,
    days_to_complete INT,
    price DOUBLE,
    reward DOUBLE,
    collateral DOUBLE,
    buyout DOUBLE,
    volume DOUBLE,
    jita_buy_value DOUBLE,
    packaged_volume DOUBLE,
    top_item_name TEXT,
    total_material_price DOUBLE,
    region_name VARCHAR(128),
    contains_unpublished INT,
    unpublished_items TEXT,
    date_discovered DATETIME,
    INDEX contracts_discovered (date_discovered),
    INDEX contracts_status_expiry (status, date_expired)
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS contract_items (
    contract_id BIGINT NOT NULL,
    row_id BIGINT NOT NULL,
    record_id BIGINT,
    item_id BIGINT,
    type_id BIGINT,
    quantity BIGINT,
    raw_quantity BIGINT,
    is_included BOOLEAN,
    is_singleton BOOLEAN,
    is_blueprint_copy BOOLEAN,
    material_efficiency INT,
    time_efficiency INT,
    runs INT,
    price DOUBLE,
    type_name TEXT,
    packaged_volume DOUBLE,
    published BOOLEAN,
    requested_price DOUBLE,
    blueprint_profit DOUBLE,
    material_price DOUBLE,
    total_price DOUBLE,
    total_volume DOUBLE,
    total_material_price DOUBLE,
    PRIMARY KEY (contract_id, row_id)
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS scanner_bootstrap (
    name VARCHAR(64) PRIMARY KEY,
    completed_at DATETIME NOT NULL
) CHARACTER SET utf8mb4;
